using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using SyWater.Notifications.Api.Security;
using SyWater.Notifications.Application.Ports.In;

namespace SyWater.Notifications.Api.Controllers;

/// <summary>Service-to-service only (X-Internal-Key): ms-iam asks to deliver the code that verifies a phone (HU-028).</summary>
[ApiController]
[AllowAnonymous]
[InternalKey]
[Route("internal/short-messages")]
public sealed class InternalShortMessagesController : ControllerBase
{
    /// <summary>
    /// Sends the code at once by the mode the user picked. 202 = the provider accepted it · 400 sms.invalid_request ·
    /// 422 sms.rejected (the number does not work for that mode: the user must fix it or pick the other mode) ·
    /// 503 sms.unavailable / sms.disabled.
    /// </summary>
    [HttpPost("verification-code")]
    public async Task<ActionResult<VerificationCodeSent>> SendVerificationCode(
        [FromBody] SendVerificationCodeRequest body, [FromServices] ISendVerificationCodeUseCase useCase, CancellationToken ct)
    {
        var providerId = await useCase.ExecuteAsync(body.To ?? "", body.Channel, body.Code ?? "", body.ValidMinutes ?? 5, ct);
        return Accepted(new VerificationCodeSent(providerId));
    }

    /// <param name="To">E.164 phone, e.g. +573001112233 (Colombia) or +593991112233 (Ecuador).</param>
    /// <param name="Channel">SMS or WHATSAPP.</param>
    /// <param name="Code">The 6-digit code generated by ms-iam.</param>
    /// <param name="ValidMinutes">How long the code lasts (said in the message). 5 by default.</param>
    public sealed record SendVerificationCodeRequest(string? To, string? Channel, string? Code, int? ValidMinutes);

    public sealed record VerificationCodeSent(string? ProviderMessageId);
}
